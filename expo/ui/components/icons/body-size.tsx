type Props = {
  bodySize: 'lean' | 'average' | 'athletic' | 'muscular' | 'heavy' | 'heavyset';
  fill?: string;
  size?: number;
}

export const BodySize = ({ bodySize, fill, size }: Props) => {
  switch (bodySize) {
    case 'lean':
      return <Lean fill={fill} size={size} />
    case 'average':
      return <Average fill={fill} size={size} />
    case 'athletic':
      return <Athletic fill={fill} size={size} />
    case 'muscular':
      return <Muscular fill={fill} size={size} />
    case 'heavy':
      return <Heavy fill={fill} size={size} />
    case 'heavyset':
      return <Heavyset fill={fill} size={size} />
    default:
      return null
  }
}
