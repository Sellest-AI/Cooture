import { constantTimeEqual, fromBase64, hmacSha256Base64 } from "../lib/crypto";
import { ActionCtx, httpAction } from "../procedures";

export { withWebhookToken } from "../lib/crypto";

/**
 * The only sanctioned way to register a webhook (03-FLAWS F2).
 *
 * `verify` has no default, so a webhook cannot be defined without deciding how the
 * request is authenticated. It runs against the *raw* body, because signatures cover
 * bytes and `JSON.parse` → `JSON.stringify` does not round-trip them.
 */
export const verifiedWebhook = <T>(opts: {
  /** Throws ⇒ 401. Must never be a no-op. */
  verify: (request: Request, rawBody: string) => Promise<void> | void;
  parse: (json: unknown) => T;
  handle: (ctx: ActionCtx, body: T, request: Request) => Promise<Response>;
}) => httpAction(async (ctx, request) => {
  const raw = await request.text();

  try {
    await opts.verify(request, raw);
  } catch (error) {
    console.warn("[webhook] rejected unauthenticated request", error);
    return new Response("Unauthorized", { status: 401 });
  }

  let body: T;
  try {
    body = opts.parse(JSON.parse(raw));
  } catch (error) {
    console.warn("[webhook] rejected malformed payload", error);
    return new Response("Bad Request", { status: 400 });
  }

  return opts.handle(ctx, body, request);
});

/**
 * Capability-token check for providers that do not sign their callbacks (RunPod) or
 * whose signing secret we do not control end to end (Replicate).
 *
 * The token is generated by us, appended to the callback URL when the job is submitted,
 * and compared here in constant time. Accepted from `?token=` or an `Authorization`
 * header so either transport works.
 *
 * `secret` is read from `env`, which throws when the variable is unset — a deployment
 * missing the secret rejects every callback rather than accepting all of them.
 */
export const verifySharedSecret = (request: Request, secret: string) => {
  const url = new URL(request.url);
  const fromQuery = url.searchParams.get("token") ?? "";
  const header = request.headers.get("authorization") ?? "";
  const fromHeader = header.startsWith("Bearer ") ? header.slice(7) : header;

  if (!constantTimeEqual(fromQuery, secret) && !constantTimeEqual(fromHeader, secret))
    throw new Error("Invalid webhook token");
};

/**
 * Standard-webhooks / svix signature scheme (`webhook-id`, `webhook-timestamp`,
 * `webhook-signature`), which is what Replicate emits.
 *
 * The signed content is `${id}.${timestamp}.${body}`; the header holds one or more
 * space-separated `v1,<base64>` entries. Timestamps older than `toleranceSeconds` are
 * rejected so captured payloads cannot be replayed indefinitely.
 */
export const verifySvixSignature = async (
  request: Request,
  rawBody: string,
  signingSecret: string,
  toleranceSeconds = 5 * 60,
) => {
  const id = request.headers.get("webhook-id");
  const timestamp = request.headers.get("webhook-timestamp");
  const signature = request.headers.get("webhook-signature");

  if (!id || !timestamp || !signature) throw new Error("Missing webhook signature headers");

  const sentAt = Number(timestamp);
  if (!Number.isFinite(sentAt)) throw new Error("Malformed webhook timestamp");
  if (Math.abs(Date.now() / 1000 - sentAt) > toleranceSeconds)
    throw new Error("Webhook timestamp outside tolerance");

  // svix secrets are `whsec_<base64>`; the base64 payload is the raw HMAC key.
  const base64Key = signingSecret.startsWith("whsec_") ? signingSecret.slice(6) : signingSecret;
  const expected = await hmacSha256Base64(fromBase64(base64Key), `${id}.${timestamp}.${rawBody}`);

  const matches = signature
    .split(" ")
    .map((part) => part.split(",")[1] ?? "")
    .some((candidate) => constantTimeEqual(candidate, expected));

  if (!matches) throw new Error("Invalid webhook signature");
};

/** HMAC-SHA256 over an arbitrary message, base64-encoded — the scheme Kie uses. */
export const verifyHmacSignature = async (message: string, signature: string, secret: string) => {
  const expected = await hmacSha256Base64(secret, message);
  if (!constantTimeEqual(signature, expected)) throw new Error("Invalid webhook signature");
};
